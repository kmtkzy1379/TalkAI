# ── R: 予測誤差とリアクション（e=予想どおり / u=予想外。同じ発話で文脈だけ変える） ─────────────
def _R(id, text, exp_hist, exp_pred, unexp_hist, unexp_pred, emotion="楽"):
    # 直近フィードバック（本番の render_last_feedback と同じ形「要約（予測差N / 感情）」）。
    # 予測差は**前のターン**の値なので、予想どおり/予想外のどちらでも同じ 20 にする（今の発話とは無関係）。
    def fb(hist):
        return f"ユーザは「{hist[-2][1]}」と話した（予測差20 / 楽）"

    return [
        S(f"{id}e", "R", text, history=exp_hist, emotion=emotion, group="expected",
          last_feedback=fb(exp_hist), last_prediction=exp_pred, expect="予想どおりの発話"),
        S(f"{id}u", "R", text, history=unexp_hist, emotion=emotion, group="unexpected",
          last_feedback=fb(unexp_hist), last_prediction=unexp_pred, expect="予想外の発話"),
    ]


