"""評価の道具専用: 「できない」と言って別の手も引き受けていない返事か（**目で見る候補を拾うだけ**）。

本番の関門（`response/orchestrator._says_cannot`）は 2026-10-09 に撤去した（ユーザ「そもそもタスクLLMに依頼出してるのは
応答AIだから。指示で制御してみる」）。語の一覧は口調が変わると当たらない（丁寧語の「調べてみますね」を引き受けと
見分けられなかった）ので本番では使わないが、記録済みの評価結果を読み直す道具がこの数え方を使っているため、
同じ式をここに残す。数字は「語で拾った候補」であって正解ではない＝最後は返事を目で見て判断する。
"""
from __future__ import annotations

import re

_CANNOT = re.compile(
    r"(?:でき|行え|起こせ|入れられ|送れ|見られ|見れ|鳴らせ|使え|扱え|触れ|届け)(?:ない|ません)"
    r"|手段(?:は|が|を)?(?:持って)?(?:い)?ない|手段(?:は|が)?無い|機能(?:は|が)?(?:ない|無い)"
)
# 旧関門の「引き受け」の語（タメ口だけ）。丁寧語（〜てみますね・〜しておきます）は拾えない＝撤去の理由
_COMMIT = re.compile(r"[るく]ね|(?:よう|そう)か|ならできる|[せれ]るよ")


def says_cannot(text: str) -> bool:
    """旧関門と同じ式（候補を拾うだけ。本番の挙動ではない）。"""
    t = text or ""
    return bool(_CANNOT.search(t)) and not _COMMIT.search(t)
