"""発話スタイル（最小・ペルソナではない）+ 読み上げ用サニタイズ。

LLM はマークダウン/箇条書きを出しがちで TTS 読み上げが不自然になる。対策は二重ゲート:
(1) system に最小スタイル指示、(2) コード側でも残留記号を除去（CLAUDE.md「規律はプロンプト
でなくコードで強制」）。ペルソナは別層で後付けする（ここには入れない）。
"""
from __future__ import annotations

import re

SPEECH_STYLE = (
    "出力は音声で読み上げられます。次を必ず守ってください。\n"
    "・話し言葉で短く自然に答える。\n"
    "・マークダウンや記号（*, #, `, 箇条書きの - や 1. など）を使わない。\n"
    "・列挙は「1つ目は…、2つ目は…」のように口頭で述べる。\n"
    "・絵文字・顔文字を使わない。\n"
    "・聞き取れない語・意味の取れない語・知らない固有名詞を、知ったかぶりで作文しない。"
    "画面が見えていて「説明して」等を求められたら推測語を無視して“実際に画面で見えているもの”を答える。"
    "それも無理なら「『○○』って聞き取れなかった、どういうこと？」と一度だけ聞き返す"
    "（同じ語を二度は聞き返さない）。知らない言葉を確信ありげに断定せず、不確かなら「たぶん」「自信ないけど」を付ける。"
)

_LEAD_MARKER = re.compile(r"^\s*(?:[-*・]|\d+[.)])\s+")  # 行頭の箇条書き/番号マーカー
_MD_CHARS = re.compile(r"[*`#]")  # 強調・コード・見出し記号


def sanitize_for_speech(text: str) -> str:
    """読み上げ前に残留マークダウン/箇条書き記号を除去（プロンプト規則の保険）。"""
    t = _LEAD_MARKER.sub("", text)
    t = _MD_CHARS.sub("", t)
    return t.strip()
