"""発話スタイル（最小・ペルソナではない）+ 読み上げ用サニタイズ。

LLM はマークダウン/箇条書きを出しがちで TTS 読み上げが不自然になる。対策は二重ゲート:
(1) system に最小スタイル指示、(2) コード側でも残留記号を除去（CLAUDE.md「規律はプロンプト
でなくコードで強制」）。ペルソナは別層で後付けする（ここには入れない）。
"""
from __future__ import annotations

import re

# 2026-09-30 ユーザ提案を実測して反映（`tools/prompt_eval/`・gpt-6-luna）:
# - 「列挙は『1つ目は…』のように」の行を外した。ルナでは有っても無くても番号読み上げは 0/18 で効いていなかった
#   （本番の旧モデル期には「1つ目はカフェ、2つ目は水族館…」とそのまま真似した記録がある）。記号・番号は上の行と
#   `sanitize_for_speech` が止める。
# - 聞き返しの見本「『○○』って聞き取れなかった、どういうこと？」を外した。本番の履歴で聞き返し6回中5回がこの文の
#   丸写しだった（「ネガシット」「リコ」「よぼだ」…）。外しても架空語への作り話は増えず（同意だけ返す割合が減った）。
SPEECH_STYLE = (
    "出力は音声で読み上げられます。次を必ず守ってください。\n"
    "・話し言葉で短く自然に答える。\n"
    "・マークダウンや記号（*, #, `, 「」, 箇条書きの - や 1. など）を使わない。\n"
    "・絵文字・顔文字を使わない。\n"
    "・聞き取れない語・意味の取れない語・知らない固有名詞を、知ったかぶりで作文しない。"
    "画面が見えていて「説明して」等を求められたら推測語を無視して“実際に画面で見えているもの”を答える。"
    "それも無理なら一度だけ聞き返す"
    "（同じ語を二度は聞き返さない）。知らない言葉を確信ありげに断定せず、不確かなら「たぶん」「自信ないけど」を付ける。"
)

# 配信中（`eve/stream/`）の版: 「短く」だけを外す（ユーザ 2026-10-15「1コメをどれだけ広げて長く話せるかが肝」
# 「でもプロンプトで縛るとその文字数辺りの応答しかできなくなり不自然かも。配信中でも短い応答は時には必要」）。
# 長さは決めない。配信の事情（コメントが無い間はイブの話が配信の中身になる等）は `# 配信` に事実として書く
SPEECH_STYLE_STREAM = SPEECH_STYLE.replace("・話し言葉で短く自然に答える。\n", "・話し言葉で自然に話す。\n")

_LEAD_MARKER = re.compile(r"^\s*(?:[-*・]|\d+[.)])\s+")  # 行頭の箇条書き/番号マーカー
_MD_CHARS = re.compile(r"[*`#]")  # 強調・コード・見出し記号
# かぎかっこ。**読み上げられない**うえに、`splitter.py` が括弧の深さを見ないため
# 「〜だよ。」の内側の句点で文が割れる（実在するハザード）。ペルソナでも禁止しているが、
# プロンプトで守られない規律はここで落とす（CLAUDE.md）。
_QUOTES = re.compile(r"[「」『』]")
# 絵文字と、モデルの特殊トークンの漏れ。上の「絵文字・顔文字を使わない」はプロンプトだけでは守られない
# （実測 2026-09-30・gpt-6-luna の応答 1308件: 絵文字 6件（👾👀🌿🌤️）・「<|END|>」「/final_element」の混入）。
# Irodori は絵文字を声の調子の合図として読むので、応答の途中に紛れると声色が勝手に変わる
# （声の調子は `tone_provider` がコード側で付ける＝ここを通らない）。
_EMOJI = re.compile("[\U0001F000-\U0001FAFF☀-➿️‍]")
_SPECIAL_TOKEN = re.compile(r"<\|[^|<>]{0,40}\|>|/?final_element|assistantfinal")
# 日本語の声では読めない文字の混入（実測 2026-10-01・gpt-6-luna の応答 2587文中 4文: 「ефонがまだ動くなら」
# 「…ずるい。եցնում」「でどう？રાજકોટмунас」＝キリル・アルメニア・グジャラート文字）。キリル〜ジョージア・
# エチオピア・クメール・アラビア/ヘブライの表示形を落とす。ギリシャ文字（α波・β版・π）とハングル（韓国語の例として
# 言うことがある）は範囲の外なので残る。
_FOREIGN_SCRIPT = re.compile(
    "[Ѐ-ჿሀ-᎟ក-៿ⴀ-ⷿꙀ-ꚟﬓ-﷿ﹰ-﻾]+")


def sanitize_for_speech(text: str) -> str:
    """読み上げ前に残留マークダウン/箇条書き記号・かぎかっこ・絵文字・特殊トークン・読めない文字を除去（プロンプト規則の保険）。"""
    t = _LEAD_MARKER.sub("", text)
    t = _MD_CHARS.sub("", t)
    t = _QUOTES.sub("", t)
    t = _SPECIAL_TOKEN.sub("", t)
    t = _EMOJI.sub("", t)
    t = _FOREIGN_SCRIPT.sub("", t)
    return t.strip()
