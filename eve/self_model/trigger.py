"""自己形成サイドカーの決定論トリガ（LLM を呼ぶ前の粗いふるい）。

## 役割分担（ユーザ裁定 2026-08-15）
- ここは**広く拾う**だけ。「趣向の話かどうか」の判断はしない。
- 精査は賢いモデル（`self_model/worker.py`）が行う。
  つまりここは **recall 優先・precision は下流**。取りこぼしだけが致命的で、
  余分に拾うのは LLM 呼び出しが1回増えるだけ（単一飛行 + watermark でまとめられる）。

## 話者ゲート（**構造的な守り**）
見るのは `speaker == "eve"` のターンだけ。実データ 2026-08-15 で、ユーザの
「俺はおかかが好き」(`conversation_history.jsonl:32`) が2か月後にイブの自己申告
(`:515`「イブはおかかかツナマヨで迷う」) に転写されていた。話者は会話履歴が構造的に
持っているので、**日本語の主語を解析する必要はない**（一人称の表記ゆれ・主語省略に
強い＝ユーザ指摘 2026-08-15 への答え）。
"""
from __future__ import annotations

import re

# ユーザ指定の合図（2026-08-15）＋実測で足した1語。
# **この1行だけを編集すれば感度が変わる**。単漢字が多く「思う」「良い」等の日常語でも
# 当たるが、それは意図どおり（広く拾って賢いモデルに精査させる方針）。
#
# 実測（`conversation_history.jsonl` のイブ発話 362件・2026-08-15）:
#   ご指定のまま        発火 53件(14.6%)  既知の自己申告 2/4  ← 取りこぼし2件
#   ＋「迷」            発火 56件(15.5%)  既知の自己申告 4/4  ← これを採用
#   ＋「迷・気分・一番」  発火 80件(22.1%)  既知の自己申告 4/4  ← 発火だけ増えて得が無い
# 取りこぼしていたのは、まさに今回の調査の発端になった2件:
#   `:515` 「コンビニおにぎりだとイブはおかかかツナマヨでちょっと**迷**っちゃうんだよね」
#   `:581` 「おにぎりならおかかとツナマヨで**迷**う」（2026-08-15 02:45 の発話）
# どちらも「好き」と言わずに好みを述べており、「迷」だけが共通の手掛かりだった。
TRIGGER_MARKERS: tuple[str, ...] = (
    "好", "嫌", "苦手", "良", "悪", "最", "思", "派", "よく", "迷",
)

_TRIGGER = re.compile("|".join(re.escape(m) for m in TRIGGER_MARKERS))

SPEAKER_EVE = "eve"


def is_trigger_text(text: str) -> bool:
    """合図の語を含むか（純関数・raise しない）。"""
    return bool(_TRIGGER.search(text or ""))


def should_examine(turns) -> bool:
    """このスパンを自己形成LLM に見せるべきか。

    条件は「**イブ自身のターン**に合図の語がある」の1つだけ。ユーザ発話は見ない
    （ユーザの好みをイブの好みとして取り込む経路を、入口で構造的に塞ぐ）。
    """
    return any(
        getattr(t, "speaker", None) == SPEAKER_EVE and is_trigger_text(getattr(t, "text", ""))
        for t in turns or []
    )
